import Foundation

/// One piece of text the keyboard kept from the clipboard.
struct ClipboardClip: Codable, Equatable, Identifiable, Sendable {
    let id: UUID
    let text: String
    /// When it was copied, or copied again. Retention counts from here.
    var copiedAt: Date
    /// Pinned clips outlive the retention window and the panel's Clear.
    var isPinned: Bool

    init(id: UUID = UUID(), text: String, copiedAt: Date, isPinned: Bool = false) {
        self.id = id
        self.text = text
        self.copiedAt = copiedAt
        self.isPinned = isPinned
    }
}

/// The rules for what the keyboard's clipboard history may keep.
///
/// Off by default and only with Full Access (see `KeyboardPreferences`). The
/// keyboard never polls the clipboard: it reads it only when the person opens
/// the clipboard panel or taps Paste, and keeps what it copies or cuts itself.
enum ClipboardHistoryPolicy {
    /// The most clips kept, pinned ones included.
    static let maximumClips = 30
    /// Longer text is not kept at all. A truncated clip would paste something
    /// that was never copied, and a page of text is not what this is for.
    static let maximumCharacters = 2_000

    /// Pasteboard types other apps use to say "do not keep this": password
    /// managers mark what they copy as concealed, and one-time or generated
    /// content as transient or auto-generated. See nspasteboard.org.
    static let doNotKeepTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        // 1Password's own marker, older than the shared convention.
        "com.agilebits.onepassword",
    ]

    /// Whether a clip with these pasteboard types may be kept.
    static func mayKeep(types: [String]) -> Bool {
        types.allSatisfy { !doNotKeepTypes.contains($0) }
    }

    /// Whether this text is worth keeping: something other than whitespace,
    /// and short enough to keep whole.
    static func mayKeep(text: String) -> Bool {
        !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
            && text.count <= maximumCharacters
    }

    /// The plain-text representations read, best first, with how each is
    /// encoded.
    static let plainTextTypes = [
        "public.utf8-plain-text",
        "public.utf16-external-plain-text",
        "public.utf16-plain-text",
        "public.plain-text",
    ]

    /// The most bytes of clipboard text decoded at all. Far above what
    /// ``maximumCharacters`` keeps — four bytes a character at the worst — so
    /// nothing keepable is refused, and far below a pasted book, which would
    /// otherwise be decoded into a `String` in a keyboard whose whole memory
    /// allowance is a few dozen megabytes, only to be thrown away.
    static let maximumBytes = 64 * 1_024

    /// The clipboard's text from its raw bytes, or nil when there are too
    /// many to be worth decoding or they do not decode.
    static func text(from data: Data, type: String) -> String? {
        guard data.count <= maximumBytes else { return nil }
        switch type {
        case "public.utf16-external-plain-text":
            // External UTF-16 carries a byte-order mark.
            return String(data: data, encoding: .utf16)
        case "public.utf16-plain-text":
            // Native byte order, which on every iPhone is little-endian.
            return String(data: data, encoding: .utf16LittleEndian)
        default:
            return String(data: data, encoding: .utf8)
        }
    }
}

/// The history itself, as a value, so every rule is testable without a file.
struct ClipboardHistory: Codable, Equatable, Sendable {
    /// Newest first.
    private(set) var clips: [ClipboardClip] = []

    init(clips: [ClipboardClip] = []) {
        self.clips = clips
    }

    /// Keeps `text`, newest first. Copying the same text again moves it to the
    /// top rather than keeping it twice, and keeps its pin.
    mutating func add(_ text: String, at now: Date) {
        guard ClipboardHistoryPolicy.mayKeep(text: text) else { return }
        if let index = clips.firstIndex(where: { $0.text == text }) {
            var clip = clips.remove(at: index)
            clip.copiedAt = now
            clips.insert(clip, at: 0)
        } else {
            clips.insert(ClipboardClip(text: text, copiedAt: now), at: 0)
        }
        trimToCapacity()
    }

    /// Drops unpinned clips older than `retention`.
    mutating func prune(retention: TimeInterval, now: Date) {
        clips.removeAll { !$0.isPinned && now.timeIntervalSince($0.copiedAt) > retention }
    }

    mutating func togglePin(_ id: UUID) {
        guard let index = clips.firstIndex(where: { $0.id == id }) else { return }
        clips[index].isPinned.toggle()
    }

    mutating func remove(_ id: UUID) {
        clips.removeAll { $0.id == id }
    }

    /// The panel's Clear: everything not pinned.
    mutating func removeUnpinned() {
        clips.removeAll { !$0.isPinned }
    }

    /// The oldest unpinned clip goes first; pinned ones go only when the
    /// history is nothing but pins.
    private mutating func trimToCapacity() {
        while clips.count > ClipboardHistoryPolicy.maximumClips {
            if let index = clips.lastIndex(where: { !$0.isPinned }) {
                clips.remove(at: index)
            } else {
                clips.removeLast()
            }
        }
    }
}

/// Where the history lives: one small file in the App Group, so the app's
/// Settings can clear what the keyboard kept. Excluded from backups and
/// protected until the phone is unlocked; never synced anywhere.
struct ClipboardHistoryStore: Sendable {
    let fileURL: URL?

    static let shared = ClipboardHistoryStore(
        fileURL: FileManager.default
            .containerURL(forSecurityApplicationGroupIdentifier: AppConfiguration.appGroupIdentifier)?
            .appendingPathComponent("keyboard-clipboard-history.json")
    )

    func load() -> ClipboardHistory {
        guard let fileURL, let data = try? Data(contentsOf: fileURL),
              let history = try? JSONDecoder().decode(ClipboardHistory.self, from: data)
        else { return ClipboardHistory() }
        return history
    }

    /// The history as it is now, with expired clips already gone.
    func current(retention: TimeInterval, now: Date = Date()) -> ClipboardHistory {
        var history = load()
        let before = history
        history.prune(retention: retention, now: now)
        if history != before { save(history) }
        return history
    }

    func save(_ history: ClipboardHistory) {
        guard let fileURL else { return }
        if history.clips.isEmpty {
            removeAll()
            return
        }
        guard let data = try? JSONEncoder().encode(history) else { return }
        do {
            try data.write(to: fileURL, options: [.atomic, .completeFileProtection])
            var url = fileURL
            var values = URLResourceValues()
            values.isExcludedFromBackup = true
            try? url.setResourceValues(values)
        } catch {
            // Nothing to report: a clip not kept is a clip not kept.
        }
    }

    /// Expired clips deleted from the file itself, not only hidden from the
    /// panel. Touches the file and nothing else — never the clipboard — so it
    /// is safe whenever the keyboard appears or the app opens. With the
    /// history off, or Full Access gone, the file goes, pins included.
    func enforce(isEnabled: Bool, retention: TimeInterval, now: Date = Date()) {
        guard let fileURL, FileManager.default.fileExists(atPath: fileURL.path) else { return }
        guard isEnabled else {
            removeAll()
            return
        }
        _ = current(retention: retention, now: now)
    }

    /// Settings' Clear, and what turning the history off does: pins too.
    func removeAll() {
        guard let fileURL else { return }
        try? FileManager.default.removeItem(at: fileURL)
    }

    /// Applies `change` to the stored history and saves it.
    @discardableResult
    func update(
        retention: TimeInterval,
        now: Date = Date(),
        _ change: (inout ClipboardHistory) -> Void
    ) -> ClipboardHistory {
        var history = load()
        history.prune(retention: retention, now: now)
        change(&history)
        save(history)
        return history
    }
}

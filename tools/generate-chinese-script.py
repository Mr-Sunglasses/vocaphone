#!/usr/bin/env python3
"""Regenerate the Simplified → Traditional Chinese tables from OpenCC.

One file, read by the Android and iOS transcript funnels from
`assets/keyboard/chinese/s2hant.tsv`. Every on-device model and most gateway
models write Mandarin in Simplified characters; these tables are what turn that
into the Traditional script a reader in Taiwan or Hong Kong expects.

The tables are OpenCC's own `s2twp` and `s2hkp` dictionaries — Traditional
characters *with* regional vocabulary, so 软件 becomes 軟體 for Taiwan and
軟件 for Hong Kong rather than the same word in other characters. The phone
runs OpenCC's algorithm over them (`ChineseScript.swift`,
`ChineseScript.kt`), which is small enough to port and needs neither its C++
nor its compiled dictionary format:

1. Normalize CJK compatibility ideographs.
2. Segment by longest match against `phrases`. A matched phrase is its own
   segment; the characters between matches are joined into one.
3. Within each segment, longest match against `phrases`, then `characters`.
4. Within each segment again, the regional tables in order, the first table
   with any match winning. A run of unmatched characters is still one
   segment, which is how 軟件 meets the Taiwan phrase table as a word.

The file is sections of `key<TAB>value` lines. `@name` starts a section and
`#` starts a comment. When OpenCC lists several values for a key, the first
is the one it uses and the only one kept.

`--verify` runs a Python copy of that algorithm against OpenCC itself over
random text built from the dictionaries' own keys, so a port that drifts from
OpenCC fails here before it ships.

Needs the OpenCC Python package at the pinned version, which brings its own
dictionaries and `opencc_dict` tool. Nothing else in the build needs it: the
table is committed, so F-Droid and CI read it from this tree.

Usage:
    uv run --with opencc==1.4.2 python tools/generate-chinese-script.py --check
    uv run --with opencc==1.4.2 python tools/generate-chinese-script.py --write
    uv run --with opencc==1.4.2 python tools/generate-chinese-script.py --verify
"""

from __future__ import annotations

import argparse
import importlib.metadata
import json
import random
import subprocess
import sys
import tempfile
from pathlib import Path

# Pinned on purpose: OpenCC's phrase tables change between releases, and a
# different word in someone's transcript should come from a reviewed diff to
# the table, not from whichever version happened to be installed.
OPENCC_VERSION = "1.4.2"

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "assets" / "keyboard" / "chinese" / "s2hant.tsv"

# Section name to the OpenCC dictionaries merged into it, in priority order: on
# a duplicate key the first dictionary's value stands, as in OpenCC's union
# group. The two regional chains are read straight from the configurations
# below, so a release that changes them fails `--check` rather than drifting.
SECTIONS = {
    "normalize": ["CJK_Compatibility_Ideographs"],
    "phrases": ["STPhrases", "STPhrases_GeneratedFromRegionalPhrases"],
    "characters": ["STCharacters"],
}
REGIONS = {"tw": "s2twp", "hk": "s2hkp"}

HEADER = (
    f"# Generated by tools/generate-chinese-script.py from OpenCC {OPENCC_VERSION}"
    " (s2twp, s2hkp). Do not edit.\n"
    "# OpenCC is Apache-2.0, https://github.com/BYVoid/OpenCC\n"
)


def _opencc():
    try:
        import opencc
    except ImportError:
        sys.exit(
            f"needs the OpenCC package: uv run --with opencc=={OPENCC_VERSION} "
            "python tools/generate-chinese-script.py ..."
        )
    installed = importlib.metadata.version("opencc")
    if installed != OPENCC_VERSION:
        sys.exit(f"needs OpenCC {OPENCC_VERSION}, found {installed}")
    return opencc


def _share(opencc) -> Path:
    return Path(opencc.__file__).parent / "clib" / "share" / "opencc"


def _files(group) -> list[str]:
    """The dictionary names in a configuration's dict or group, in order."""
    if group["type"] == "group":
        return [name for item in group["dicts"] for name in _files(item)]
    return [group["file"].removesuffix(".ocd2")]


def _chain(opencc, config: str) -> list[list[str]]:
    """Each conversion stage's dictionaries, after checking the shape."""
    spec = json.loads((_share(opencc) / f"{config}.json").read_text())
    stages = [_files(stage["dict"]) for stage in spec["conversion_chain"]]
    expected = SECTIONS["phrases"] + SECTIONS["characters"]
    if (
        _files(spec["segmentation"]["dict"]) != SECTIONS["phrases"]
        or [_files(n["dict"]) for n in spec["normalization"]] != [SECTIONS["normalize"]]
        or len(stages) != 2
        or stages[0] != expected
    ):
        sys.exit(f"{config}.json no longer has the shape this port implements")
    return stages


def _dictionary(opencc, name: str) -> dict[str, str]:
    """One compiled dictionary as key → first value, via OpenCC's own tool."""
    tool = Path(opencc.__file__).parent / "clib" / "bin" / "opencc_dict"
    with tempfile.TemporaryDirectory() as scratch:
        text = Path(scratch) / f"{name}.txt"
        subprocess.run(
            [
                str(tool),
                "-i", str(_share(opencc) / f"{name}.ocd2"),
                "-o", str(text),
                "-f", "ocd2",
                "-t", "text",
            ],
            check=True,
        )
        entries: dict[str, str] = {}
        for line in text.read_text(encoding="utf-8").splitlines():
            if not line:
                continue
            key, values = line.split("\t", 1)
            entries[key] = values.split(" ", 1)[0]
        return entries


def sections(opencc) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for section, names in SECTIONS.items():
        merged: dict[str, str] = {}
        for name in names:
            for key, value in _dictionary(opencc, name).items():
                merged.setdefault(key, value)
        out[section] = merged
    for region, config in REGIONS.items():
        for index, name in enumerate(_chain(opencc, config)[1]):
            out[f"{region}{index + 1}"] = _dictionary(opencc, name)
    return out


def render(tables: dict[str, dict[str, str]]) -> str:
    lines = [HEADER]
    for section, entries in tables.items():
        lines.append(f"@{section}\n")
        lines.extend(f"{key}\t{entries[key]}\n" for key in sorted(entries))
    return "".join(lines)


# The algorithm the apps run, in Python, for --verify.


class _Table:
    def __init__(self, entries: dict[str, str]):
        self.entries = entries
        self.longest = max((len(key) for key in entries), default=0)

    def match(self, text: str, start: int) -> tuple[int, str] | None:
        for length in range(min(self.longest, len(text) - start), 0, -1):
            value = self.entries.get(text[start:start + length])
            if value is not None:
                return length, value
        return None


def _convert_with(text: str, tables: list[_Table]) -> str:
    out = []
    i = 0
    while i < len(text):
        found = None
        for table in tables:
            found = table.match(text, i)
            if found:
                break
        if found:
            out.append(found[1])
            i += found[0]
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def convert(text: str, tables: dict[str, dict[str, str]], region: str) -> str:
    normalize = _Table(tables["normalize"])
    phrases = _Table(tables["phrases"])
    characters = _Table(tables["characters"])
    regional = [
        _Table(tables[name]) for name in tables if name.startswith(region)
    ]
    text = _convert_with(text, [normalize])
    segments: list[str] = []
    run_start = None
    i = 0
    while i < len(text):
        found = phrases.match(text, i)
        if found:
            if run_start is not None:
                segments.append(text[run_start:i])
                run_start = None
            segments.append(text[i:i + found[0]])
            i += found[0]
        else:
            if run_start is None:
                run_start = i
            i += 1
    if run_start is not None:
        segments.append(text[run_start:])
    return "".join(
        _convert_with(_convert_with(segment, [phrases, characters]), regional)
        for segment in segments
    )


def verify(opencc, tables: dict[str, dict[str, str]], samples: int) -> int:
    converters = {region: opencc.OpenCC(config) for region, config in REGIONS.items()}
    rng = random.Random(0)
    pieces = (
        sorted(tables["phrases"])
        + sorted(tables["characters"])
        # Simplified spellings of the regional phrases, so the regional stage
        # sees its own keys and not only what the phrase table happens to hold.
        + sorted({opencc.OpenCC("t2s").convert(k) for n in tables if n[:2] in REGIONS for k in tables[n]})
        + list("，。？！ abc 123")
    )
    failures = 0
    for _ in range(samples):
        text = "".join(rng.choice(pieces) for _ in range(rng.randint(1, 10)))
        for region, converter in converters.items():
            expected = converter.convert(text)
            actual = convert(text, tables, region)
            if actual != expected:
                failures += 1
                if failures <= 10:
                    print(f"{region}: {text!r} -> {actual!r}, OpenCC {expected!r}")
    print(f"{failures} of {samples * len(converters)} conversions differ from OpenCC")
    return 1 if failures else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the table")
    mode.add_argument(
        "--check", action="store_true", help="exit non-zero if the table is stale"
    )
    mode.add_argument(
        "--verify",
        type=int,
        nargs="?",
        const=20000,
        metavar="SAMPLES",
        help="compare the ported algorithm with OpenCC on random text",
    )
    arguments = parser.parse_args()

    opencc = _opencc()
    tables = sections(opencc)
    if arguments.verify:
        return verify(opencc, tables, arguments.verify)
    text = render(tables)
    if arguments.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current != text:
        print(
            f"{OUTPUT.relative_to(ROOT)} is stale: run "
            "tools/generate-chinese-script.py --write",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

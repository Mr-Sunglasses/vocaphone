#!/usr/bin/env python3
"""Writes assets/grammar/parity_fixtures.json, the file both apps test against.

    python3 fixtures.py MODEL_DIR           # write
    python3 fixtures.py MODEL_DIR --check   # fail if the checked-in file is stale

Each case records every pass the reference made: the words, the token ids
(an exact-match target for the Kotlin and Swift tokenizers), the label the
model picked after the KEEP bias, the label the guard allowed, and the final
text. `tokenizer` adds words that only exercise the BPE.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from infer import KEEP_BIAS, MAX_PASSES, MAX_TOKENS, Tagger

HERE = Path(__file__).parent
OUT = HERE.parent.parent / "assets" / "grammar" / "parity_fixtures.json"
REVISION = "e58cbb68c382a894a9f6de704fe385ec260f0949"
FILES = ["mindtype_tagger.onnx", "tokenizer.json", "labels.json", "plausible_pairs.json", "config.json"]

CASES: list[tuple[str, list[str]]] = [
    # Fixed in one pass.
    ("He don't know where the keys are.", []),
    ("She go to school every day.", []),
    ("We was at the park all afternoon.", []),
    ("I need a umbrella.", []),
    ("He bought an new car.", []),
    ("Their going to be late.", []),
    ("I think there car broke down.", []),
    ("Its going to rain later.", []),
    ("The dog wagged it's tail.", []),
    ("Is this you're phone?", []),
    ("She is taller then me.", []),
    ("That's to expensive.", []),
    ("I could of told you that.", []),
    ("I want go home.", []),
    ("I seen that movie.", []),
    ("He brung his guitar.", []),
    ("i has a apple.", []),
    # Left alone.
    ("Can you call me back when you get this?", []),
    ("I want to come too.", []),
    ("Their house is the blue one on the corner.", []),
    ("I'd rather walk than take the bus.", []),
    ("Lol okay see you then.", []),
    ("Send a thumbs up emoji to the group.", []),
    ("Open the garage door.", []),
    # Protected spans, numbers and names.
    ("Check example.com, its all there.", []),
    ("I sent it to jane@example.com but she don't reply.", []),
    ("He don't have the docs at https://docs.example.com yet.", []),
    ("The total came to $42.50 with tip.", []),
    ("Tell Kevin its at 7:30.", []),
    ("Your flight UA 2041 are on time.", []),
    ("The deadline is March 31st.", []),
    ("The U.S. office opens at 9.", []),
    # Custom vocabulary.
    ("I pushed the fix to Vocagate this morning.", ["Vocagate"]),
    ("brb grabbing coffee.", ["brb"]),
    # Several sentences, odd whitespace, curly apostrophes.
    ("He don't know about the party yet, so don't tell him. Its at Maria's place on Friday at 8.", []),
    ("Their going to be late!  I think its fine.", []),
    ("He don’t know.", []),
    ("He don’t know.", ["don't"]),
    # Nothing the model may touch.
    ("今天天气很好。", []),
    ("👍 🎉", []),
    ("...", []),
    ("", []),
]

TOKENIZER_WORDS = [
    "the", "The", "don't", "don’t", "it's", "they're", "you're", "Mohammed", "Priya",
    "Shinjuku", "UA", "2041", "42", ",", ".", "?", "!", "$", "@", "'", "0",
    "café", "naïve", "今天", "👍", "🇺🇸", "supercalifragilistic", "kubectl", "a" * 40,
]


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def boundary_case(t: Tagger) -> str:
    """A sentence long enough to need two chunks, with a name as the second
    chunk's first word: the guard must still treat it as mid-sentence."""
    words, tokens = ["So"], len(t.encode_word("So"))
    filler = ["and", "then", "we", "went"]
    while tokens < MAX_TOKENS:
        w = filler[len(words) % len(filler)]
        k = len(t.encode_word(w))
        if tokens + k > MAX_TOKENS:
            break
        words.append(w)
        tokens += k
    return " ".join(words + ["Kevin", "said", "he", "don't", "know."])


# A URL longer than the model can read on its own, beside a fixable slip.
LONG_URL = "https://example.com/" + "/".join(f"segment{i}" for i in range(60))


def build(model_dir: Path) -> str:
    t = Tagger(model_dir)
    cases = []
    extra = [(boundary_case(t), []), (f"He don't know where {LONG_URL} went.", [])]
    for text, vocabulary in CASES + extra:
        r = t.correct(text, frozenset(vocabulary))
        cases.append({
            "input": text,
            "vocabulary": vocabulary,
            "output": r.output,
            "sentences": [
                [{
                    "words": p.words,
                    "ids": p.ids,
                    "starts": p.starts,
                    "labels": [d.label for d in p.decisions],
                    "chosen": [d.chosen for d in p.decisions],
                } for p in passes]
                for passes in r.passes
            ],
        })
    doc = {
        "about": "Generated by tools/grammar-eval/fixtures.py. Do not edit by hand.",
        "model": {
            "repository": "Mindscend/mindtype-tagger-v2.0",
            "revision": REVISION,
            "sha256": {f"onnx/{f}": sha256(model_dir / f) for f in FILES},
        },
        "recipe": {"bos_id": 1, "keep_bias": KEEP_BIAS, "max_passes": MAX_PASSES,
                   "max_tokens": MAX_TOKENS},
        "tokenizer": [{"word": w, "ids": t.encode_word(w)} for w in TOKENIZER_WORDS],
        "cases": cases,
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("model_dir", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = build(args.model_dir)
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT} is stale; run fixtures.py without --check")
        print(f"{OUT.name} is current")
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(CASES) + 2} cases)")


if __name__ == "__main__":
    main()

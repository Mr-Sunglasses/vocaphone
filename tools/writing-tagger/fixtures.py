#!/usr/bin/env python3
"""Writes assets/grammar/pos_fixtures.json: what the reference tagger says.

    python3 fixtures.py           # write
    python3 fixtures.py --check   # fail if the checked-in file is stale

`PosTagger.kt` and `PosTagger.swift` must tag every sentence exactly as
`postag.py` does with `assets/keyboard/en-pos.bin`. The sentences cover what
the agreement checks lean on: subjects and their verbs, typed in lower case
and with the very mistakes being looked for.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "grammar-eval"))

from postag import Model, fnv  # noqa: E402
from writing_text import tokenize  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "assets" / "keyboard" / "en-pos.bin"
OUT = ROOT / "assets" / "grammar" / "pos_fixtures.json"

SENTENCES = [
    "The kids plays outside every day.",
    "My sister live in London.",
    "Each of the boys have a bike.",
    "The price of the tickets have gone up.",
    "Everyone are invited to the party.",
    "Where is my keys?",
    "There is two cars outside.",
    "She walk to work every morning.",
    "he always forget his keys",
    "I goes to the gym",
    "Mike have the tickets for Friday.",
    "The news is good, and Physics is hard.",
    "my mom and dad is coming",
    "I don't think it's John's car, it's Mary’s.",
    "We met at 3:00 in 2026 and paid $12.50 for 2 coffees!!",
    "Björn said the café was great 😊",
    "LOL that's SO funny, BTW the iPhone works",
    "Can you send me the report by Friday?",
    "I go to the gym yesterday",
    "The dog wagged its tail and the cats were asleep.",
    "we've been waiting for an hour",
    "If you need anything, let me know.",
    "The team is meeting the client at noon.",
    "a well-known co-worker e-mailed me",
]


def build() -> str:
    model = Model.from_bytes(MODEL.read_bytes())
    cases = []
    for s in SENTENCES:
        words = [t.text for t in tokenize(s)]
        cases.append({"text": s, "words": words, "tags": model.tag(words)})
    doc = {
        "about": "Generated by tools/writing-tagger/fixtures.py from assets/keyboard/en-pos.bin. "
                 "PosTagger.kt and PosTagger.swift must tag each sentence exactly so.",
        "fnv": [{"text": t, "hash": f"{fnv(t):016x}"} for t in ["", "b", "w the", "t1w -START- don't", "s é"]],
        "cases": cases,
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main() -> None:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.name} is stale; run tools/writing-tagger/fixtures.py")
        print(f"{OUT.name} is current")
        return
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(SENTENCES)} sentences)")


if __name__ == "__main__":
    main()
